const fs = require('fs');
const path = require('path');

const root = __dirname;
const imagesDir = path.join(root, 'images');
const outputFile = path.join(root, 'background-images.js');
const allowedExtensions = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif']);

const files = fs.readdirSync(imagesDir)
  .filter(file => allowedExtensions.has(path.extname(file).toLowerCase()))
  .sort((a, b) => {
    if (a === 'image_low.jpg') return -1;
    if (b === 'image_low.jpg') return 1;
    return a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' });
  });

const contents = [
  '// Generated by sync-backgrounds.js. Do not edit by hand.',
  `window.BACKGROUND_IMAGES = ${JSON.stringify(files, null, 2)};`,
  '',
].join('\n');

fs.writeFileSync(outputFile, contents);
console.log(`Wrote ${files.length} background image(s) to background-images.js`);
